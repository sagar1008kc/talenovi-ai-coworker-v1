"""Voice roster: role-named ElevenLabs voices discovered from .env.

Convention: one env var per role, `ELEVENLABS_<ROLE>_VOICE_ID`, e.g. ELEVENLABS_CHILD_GIRL_VOICE_ID,
ELEVENLABS_SERIOUS_WOMAN_VOICE_ID, ELEVENLABS_NARRATOR_VOICE_ID. Characters point their bible
`env_key` at a role, so casting picks the best available role per character.

The roster cache (config/voice_roster.json) stores role names and public voice labels only,
never voice IDs or API keys.
"""
from __future__ import annotations

import json
from pathlib import Path
import re
from typing import Any, Callable

ROLE_PATTERN = re.compile(r"^ELEVENLABS_([A-Z0-9_]+?)_VOICE_ID$")
# Legacy variables that are aliases or per-character keys, not roster roles.
NON_ROLE_KEYS = {"ELEVENLABS_VOICE_ID"}


def roster_keys(env: dict[str, str | None]) -> dict[str, str]:
    """role name -> env var name, for every non-empty ELEVENLABS_<ROLE>_VOICE_ID."""
    roles = {}
    for key, value in env.items():
        match = ROLE_PATTERN.match(key)
        if match and key not in NON_ROLE_KEYS and value and not value.startswith("${"):
            roles[match.group(1).lower()] = key
    return dict(sorted(roles.items()))


def describe_roster(env: dict[str, str | None], fetch: Callable[[str], dict | None]) -> list[dict[str, Any]]:
    """Look up each role's voice (free metadata call). `fetch(voice_id)` returns the API JSON or None."""
    rows, seen = [], {}
    for role, key in roster_keys(env).items():
        voice_id = env[key] or ""
        info = fetch(voice_id)
        labels = (info or {}).get("labels") or {}
        rows.append({
            "role": role, "env_key": key, "found_in_account": info is not None,
            "voice_name": (info or {}).get("name"), "category": (info or {}).get("category"),
            "gender": labels.get("gender"), "age": labels.get("age"), "accent": labels.get("accent"),
            "description": labels.get("descriptive") or labels.get("use_case"),
            "same_voice_as": seen.get(voice_id),
        })
        seen.setdefault(voice_id, role)
    return rows


def elevenlabs_fetcher(api_key: str) -> Callable[[str], dict | None]:
    import requests

    def fetch(voice_id: str) -> dict | None:
        resp = requests.get(f"https://api.elevenlabs.io/v1/voices/{voice_id}",
                            headers={"xi-api-key": api_key}, timeout=30)
        return resp.json() if resp.ok else None
    return fetch


def write_roster(root: Path, rows: list[dict]) -> Path:
    path = root / "config" / "voice_roster.json"
    path.write_text(json.dumps({"note": "Generated by `python main.py voices`. Role names and public labels "
                                        "only; IDs stay in .env.", "roles": rows}, indent=2) + "\n",
                    encoding="utf-8")
    return path


def missing_speaker_voices(bible: Any, env: dict[str, str | None], speakers: set[str]) -> list[str]:
    """Env keys required by this episode's speakers that are not set."""
    return sorted({bible.voices[s].env_key for s in speakers if not env.get(bible.voices[s].env_key)})
